/** 1. React surface: server-rendered, every anchor in the initial HTML. */
export function renderReact(manifest) {
  const checksum = manifestChecksum(manifest)
  const items = publicMembers(manifest)
    .map((m) => `      <li className="apps-menu__item">\n        <a className="apps-menu__link" href="${esc(m.url)}">\n          <span className="apps-menu__name">${esc(m.name)}</span>\n          <span className="apps-menu__blurb">${esc(m.blurb)}</span>\n        </a>\n      </li>`)
    .join('\n')
  return `// ${header('react', checksum)}
// The apps menu pane: a second burger, always, desktop included. It reuses
// the existing mobile-menu state machine (aria-expanded, Escape closes,
// focus returns) rather than inventing a second one.
import { useEffect, useRef, useState } from 'react'

const MEMBERS = ${JSON.stringify(publicMembers(manifest).map((m) => ({ name: m.name, url: m.url, blurb: m.blurb, id: m.id })), null, 2)}

export default function AppsMenu() {
  const [open, setOpen] = useState(false)
  const ref = useRef(null)
  useEffect(() => {
    if (!open) return undefined
    const onKey = (e) => { if (e.key === 'Escape') setOpen(false) }
    document.addEventListener('keydown', onKey)
    return () => document.removeEventListener('keydown', onKey)
  }, [open])
  return (
    <div className="apps-menu" ref={ref}>
      <style>{STYLE}</style>
      <button
        type="button"
        className="apps-menu__toggle"
        aria-expanded={open}
        aria-controls="apps-menu-pane"
        aria-label="Apps menu"
        onClick={() => setOpen((v) => !v)}
      >
        <span className="apps-menu__grid" aria-hidden="true">\u22ef</span>
      </button>
      <nav id="apps-menu-pane" className="apps-menu__pane" hidden={!open} aria-label="Suite apps" data-i18n="apps.menu.label" data-i18n-default="en">
        <ul className="apps-menu__list">
${items}
        </ul>
      </nav>
    </div>
  )
}
// PRD 5: the pane carries its own styling, so the emitted bytes are
// self-contained (no host CSS needed) and every color rides the tokens.
// S5 (G8): the :focus-visible rule is the pane's keyboard-usable floor.
const STYLE = \`${PANE_CSS}\`
`
}

/** 2. Partial surface: pure HTML+CSS, zero JS, Jekyll include. */
export function renderPartial(manifest) {
  const checksum = manifestChecksum(manifest)
  const items = publicMembers(manifest)
    .map((m) => `      <li class="apps-menu__item">\n        <a class="apps-menu__link" href="${esc(m.url)}">\n          <span class="apps-menu__name">${esc(m.name)}</span>\n          <span class="apps-menu__blurb">${esc(m.blurb)}</span>\n        </a>\n      </li>`)
    .join('\n')
  // S5 (G8): the pane carries a named landmark, real anchors, a visible
  // focus ring, and keyed chrome strings with an explicit locale fallback.
  return `<!-- ${header('partial', checksum)} -->
<nav class="apps-menu" aria-label="Suite apps" data-i18n="apps.menu.label" data-i18n-default="en">
  <ul class="apps-menu__list">
${items}
  </ul>
</nav>
<style>
${PANE_CSS}
</style>
`
}

/** 3. README surface: a generated markdown table snippet. */
export function renderReadme(manifest) {
  const checksum = manifestChecksum(manifest)
  const rows = publicMembers(manifest)
    .map((m) => `| [${m.name}](${m.url}) | ${m.blurb} | ${m.status} |`)
    .join('\n')
  return `<!-- ${header('readme', checksum)} -->
| Member | What it is | Status |
|---|---|---|
${rows}
`
}

/** 4. Registry surface: machine-readable manifest export. */
export function renderRegistry(manifest) {
  const checksum = manifestChecksum(manifest)
  const address = rollupAddress(manifest)
  const { needs, dependents } = buildGraph(manifest)
  const members = manifest.members.map((m) => ({
    id: m.id,
    name: m.name,
    role: m.role,
    url: m.url,
    blurb: m.blurb,
    status: m.status,
    ...(m.npm ? { npm: m.npm } : {}),
    ...(m.repo ? { repo: m.repo } : {}),
  }))
  return JSON.stringify({
    schemaVersion: 1,
    // PRD 5.1: apps.json is the canonical source; the roll-up is ONE
    // rendering of it. `generated.manifest` is the copy a consumer proves.
    generated: { by: 'govstruct', surface: 'registry', manifest: checksum },
    address,
    family: manifest.family,
    memberCount: manifest.memberCount,
    order: manifest.order,
    graph: manifest.order.map((id) => ({ id, needs: needs.get(id) ?? [], neededBy: dependents.get(id) ?? [] })),
    members,
    byRole: countBy(manifest.members, 'role'),
    byStatus: countBy(manifest.members, 'status'),
  }, null, 2) + '\n'
}

/**
 * The canonical composed manifest (PRD 5.1): members + compliance blocks +
 * meta. `registry.json` is one rendering of THIS. Carries the roll-up
 * address/cache contract so a consumer pins the shape it knows.
 */
export function renderApps(manifest, compliance = {}) {
  const checksum = manifestChecksum(manifest)
  return JSON.stringify({
    schemaVersion: 1,
    generated: { by: 'govstruct', surface: 'apps', manifest: checksum },
    address: rollupAddress(manifest),
    family: manifest.family,
    memberCount: manifest.memberCount,
    order: manifest.order,
    members: manifest.members,
    compliance,
  }, null, 2) + '\n'
}

function countBy(items, key) {
  const out = {}
  for (const i of items) out[i[key]] = (out[i[key]] ?? 0) + 1
  return out
}

export const SURFACES = {
  apps: renderApps,
  react: renderReact,
  partial: renderPartial,
  readme: renderReadme,
  registry: renderRegistry,
}
